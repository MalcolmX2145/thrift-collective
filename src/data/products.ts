export const getProductsByCollection = (type: string): Product[] => {
  switch (type) {
    case 'new-arrivals':
      return mockProducts.filter(p => p.isNew && !p.isSold).slice(0, 8);
    case 'trending':
      return mockProducts.filter(p => p.isTrending && !p.isSold).slice(0, 8);
    case 'premium':
      return mockProducts.filter(p => p.isPremium && !p.isSold).slice(0, 8);
    case 'deals':
      return mockProducts.filter(p => (p.isDeal || p.price <= 500) && !p.isSold).slice(0, 8);
    case 'jackets':
      return mockProducts.filter(p => p.subCategory === 'JACKETS' && !p.isSold).slice(0, 8);
    default:
      return mockProducts.filter(p => !p.isSold).slice(0, 8);
  }
};

export const getProductById = (id: string): Product | undefined => {
  return mockProducts.find(p => p.id === id);
};

export const getProductsByCategory = (category: string): Product[] => {
  return mockProducts.filter(p => 
    p.category.toLowerCase() === category.toLowerCase() && !p.isSold
  );
};

export const getSimilarProducts = (product: Product): Product[] => {
  return mockProducts
    .filter(p => 
      p.id !== product.id && 
      (p.category === product.category || p.subCategory === product.subCategory) &&
      !p.isSold
    )
    .slice(0, 4);
};
